"""子代理定义。

只有一个 critic。原 demo5 的 researcher 被删掉，原因不是"不需要调研"，而是：
证据必须经 evidence_add 落库，而子代理与主 Agent 并发写同一个 SQLite 会抢锁；
单类深挖是低频路径，不值得为它付并发的复杂度（见 docs/项目计划 的 D6）。
"""

from __future__ import annotations

CRITIC_PROMPT = """你是一名挑剔但建设性的审稿人，审的是「AI 行业研判简报」。

只检查格式校验工具查不到的四件事：
1. 术语处理是否匹配受众（非专业档出现架构名词、业内档出现科普铺垫，都算错）
2. 判断是否空洞——去掉证据后，这条判断是否仍然成立？成立说明它没信息量
3. 依赖假设是否真的被依赖——如果假设不成立，判断会不会倒？不会说明假设是装饰
4. 推翻条件是否可观测——"如果行业发展不及预期"这类不可观测的条件等于没写

不要检查：字数、条数、格式、有没有日期、有没有链接。那些由 brief_lint 负责。

输出：最多 5 条，按严重程度排序，每条指明是哪一条主线、问题在哪、怎么改。
不要重写全文，不要夸。"""


def build_subagents(sub_model) -> list[dict]:
    return [
        {
            "name": "critic",
            "description": (
                "审稿人。简报写完后，把全文放进任务描述里交给它，"
                "它只报格式校验查不到的问题：术语错档、判断空洞、假设是装饰、推翻条件不可观测。"
            ),
            "system_prompt": CRITIC_PROMPT,
            "tools": [],
            "model": sub_model,
        },
    ]
